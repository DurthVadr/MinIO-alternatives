#!/usr/bin/env python3
"""Render results/<profile-id>/ into a RESULTS.md.

    make_results.py [profile-id] [-o out.md]

Defaults to the only profile directory under results/ when there is exactly
one, and to RESULTS.md at the repository root.

WHY THIS IS GENERATED
---------------------
Every number in RESULTS.md is read out of the JSON under results/. None of it
is typed in. That matters more here than it usually would: the two mistakes
this project came closest to publishing were both a human copying a number or
a system name out of one file and into prose. A generated table cannot drift
from the data it claims to summarise, and re-running this after new results
land is a regeneration rather than an edit.

The holes are generated too. A (system, config, profile) cell with no result
file is printed as "no result" in the table where it belongs, not omitted --
an absent row reads as "not applicable", and these absences are findings.
"""
import argparse
import json
import os
import sys

import yaml

MIB = 1024 * 1024
SYSTEM_ORDER = ["minio", "silo", "rustfs", "seaweedfs"]
CONFIG_LABEL = {"c1": "c1 · no redundancy", "c2": "c2 · redundant"}

# The op whose latency is the measured one, per warp op. `mixed` runs four
# operations and reporting one of them as "the" latency would be a choice
# disguised as a fact, so both sides of the read/write pair are reported.
MEASURED_OPS = {
    "mixed": ("GET", "PUT"),
    "get": ("GET",),
    "put": ("PUT",),
    "multipart-put": ("PUTPART",),
    "list": ("LIST",),
}

STATUS_GLYPH = {
    "supported": "+",
    "diverges": "~",
    "accepted_not_enforced": "!",
    "not_implemented": "-",
    "not_exercisable": "n/a",
}

STATUS_MEANING = [
    ("+", "supported", "Behaves the way AWS documents it."),
    ("~", "diverges", "Implemented, but the behaviour is visibly different."),
    ("!", "accepted_not_enforced",
     "Accepts the call and returns success without enforcing the guarantee it implies."),
    ("-", "not_implemented", "Absent, and says so."),
    ("n/a", "not_exercisable",
     "The system behaves correctly; this setup cannot exercise the behaviour."),
]


# ---------------------------------------------------------------------------
# Loading
# ---------------------------------------------------------------------------

def load_runs(raw_dir):
    """Every result file in raw/, keyed by (system, config, profile, round).

    warp's own analysis output lands in the same directory as
    `<run>.warp-analysis.json`. It is not a result file and has none of the
    keys below, so it is skipped by suffix rather than by trying to parse it.
    """
    runs = {}
    if not os.path.isdir(raw_dir):
        return runs
    for name in sorted(os.listdir(raw_dir)):
        if not name.endswith(".json") or name.endswith(".warp-analysis.json"):
            continue
        with open(os.path.join(raw_dir, name)) as fh:
            result = json.load(fh)
        run = result["run"]
        key = (run["system"], run["config"], run["profile"], run["round"])
        runs[key] = result
    return runs


def load_workloads(root):
    with open(os.path.join(root, "bench", "workloads.yaml")) as fh:
        return yaml.safe_load(fh)


# ---------------------------------------------------------------------------
# Markdown helpers
# ---------------------------------------------------------------------------

def table(headers, rows, right=()):
    """A markdown table. `right` holds the indices of right-aligned columns."""
    sep = ["---:" if i in right else "---" for i in range(len(headers))]
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(sep) + " |"]
    for row in rows:
        out.append("| " + " | ".join("" if c is None else str(c) for c in row) + " |")
    return "\n".join(out)


def num(value, digits=1):
    if value is None:
        return "—"
    return f"{value:,.{digits}f}"


def systems_in(*mappings):
    """SYSTEM_ORDER first, then anything else, so an added system still shows."""
    seen = set()
    for mapping in mappings:
        seen |= set(mapping)
    ordered = [s for s in SYSTEM_ORDER if s in seen]
    return ordered + sorted(seen - set(ordered))


