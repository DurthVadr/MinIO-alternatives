def latency_cell(result, op):
    by_op = (result.get("metrics") or {}).get("by_op") or {}
    latency = (by_op.get(op) or {}).get("latency") or {}
    request = latency.get("request_millis") or {}
    if not request:
        return None, None
    return request.get("p50"), request.get("p99")


def profile_rows(workloads, profile, runs, systems, rnd):
    """One row per (config, system), including the cells that have no result."""
    warp_op = profile["op"]
    ops = MEASURED_OPS.get(warp_op, ())
    is_list = warp_op == "list"
    rows = []
    for config in sorted(CONFIG_LABEL):
        measured = []
        for system in systems:
            result = runs.get((system, config, profile["id"], rnd))
            if result is None:
                measured.append((system, None, None, None))
                continue
            metrics = result.get("metrics") or {}
            total = metrics.get("total") or {}
            if is_list:
                # A LIST response carries no object bytes, so MiB/s is
                # meaningless here and the run's byte counter belongs to the
                # preparation phase. Report the two rates that do mean
                # something: keys returned per second, and LIST calls per
                # second. warp counts listed keys as "objects" for this op.
                listed = (metrics.get("by_op") or {}).get("LIST") or {}
                duration = listed.get("measure_duration_seconds") or 0
                primary = listed.get("obj_per_sec_avg")
                secondary = listed["requests"] / duration if duration else None
            else:
                primary = total.get("bytes_per_sec_avg")
                primary = primary / MIB if primary else primary
                secondary = total.get("obj_per_sec_avg")
            measured.append((system, primary, secondary, result))
        measured.sort(key=lambda m: (m[1] is None, -(m[1] or 0)))
        for system, primary, secondary, result in measured:
            if result is None:
                rows.append([config, system, "*no result*", "", "", "", ""])
                continue
            total = (result.get("metrics") or {}).get("total") or {}
            lat = []
            for op in ops:
                p50, p99 = latency_cell(result, op)
                lat.append(f"{op} {num(p50)} / {num(p99)}" if p50 is not None else "—")
            rows.append([
                config,
                system,
                num(primary, 0 if is_list else 1) if primary is not None else "—",
                num(secondary) if secondary is not None else "—",
                " · ".join(lat) if lat else "—",
                total.get("errors") if total.get("errors") else "",
                f"`{result['status']}`" if result["status"] != "ok" else "",
            ])
    return rows


def section_performance(workloads, runs, systems):
    rnd = 1
    lines = [
        "## Performance",
        "",
        "### How to read this section",
        "",
        "The design called for three interleaved rounds and a median. "
        f"**What exists is round {rnd}, once.** Warm-up and ordering effects "
        "are therefore uncontrolled, and the data contains direct evidence "
        "that they matter: on `bigdata-get`, both Silo and RustFS measured "
        "*faster* in their redundant configuration than in their "
        "single-device one. Erasure coding cannot make a read cheaper, so "
        "something other than the storage configuration is moving those "
        "numbers by that much.",
        "",
        "Read the tables comparatively within a row group, treat differences "
        "under roughly 20% as noise, and do not quote any single number as a "
        "property of the software. Absolute values belong to this hardware.",
        "",
        "Latency is the end-to-end request duration for the measured "
        "operation, in milliseconds, as `p50 / p99`. It is computed from "
        "warp's per-request records, not by averaging its 10-second window "
        "summaries — percentiles cannot be averaged across windows, and doing "
        "it inflated the median of one run by 3.8x before it was caught.",
        "",
        "`errors` is warp's own error counter. A run can carry a handful of "
        "them and still read `ok`: the error-rate checks have thresholds, and "
        "warp counts some of its own record-keeping faults there too. A run "
        "whose errors mattered appears under "
        "[Runs that are not clean](#runs-that-are-not-clean).",
        "",
        "An empty cell is a hole in the matrix, not a zero. `*no result*` "
        "means the combination was never run; a row with a `failed` status "
        "means it was run and did not produce a usable measurement.",
        "",
    ]

    for profile in workloads["profiles"]:
        rows = profile_rows(workloads, profile, runs, systems, rnd)
        args = " ".join(profile.get("args", []))
        duration = profile.get("duration_seconds",
                               workloads["defaults"]["duration_seconds"])
        concurrency = workloads["defaults"]["concurrency"]
        is_list = profile["op"] == "list"
        lines += [
            f"### `{profile['id']}`",
            "",
            f"`warp {profile['op']} {args}` · {duration}s · "
            f"concurrency {concurrency}",
            "",
            table(
                ["Config", "System",
                 "keys/s" if is_list else "MiB/s",
                 "LIST req/s" if is_list else "obj/s",
                 "latency p50 / p99 (ms)", "errors", "status"],
                rows,
                right={2, 3, 5},
            ),
            "",
        ]
        if is_list:
            lines += [
                "MiB/s is omitted for this profile: a LIST response carries no "
                "object bytes, and the run's byte counter belongs to the "
                "preparation phase rather than to the measured one. `keys/s` "
                "is keys returned, `LIST req/s` is calls served.",
                "",
            ]

    degraded = [(k, r) for k, r in sorted(runs.items()) if r["status"] != "ok"]
    lines += ["### Runs that are not clean", ""]
    if not degraded:
        lines.append("None. Every recorded run passed every check.")
    else:
        rows = []
        for (system, config, profile_id, _), result in degraded:
            failed = [c["name"] for c in result.get("checks", []) if not c["ok"]]
            rows.append([
                f"{system} / {config} / {profile_id}",
                f"`{result['status']}`",
                ", ".join(f"`{f}`" for f in failed) or "—",
            ])
        lines += [
            "A run is downgraded out of `ok` by *any* failing check, including "
            "warning-level ones. A benchmark client that becomes the "
            "bottleneck measures the client, so a run that trips that check is "
            "not a clean measurement of storage even though warp exited zero.",
            "",
            table(["Run", "Status", "Failing checks"], rows),
        ]

    return "\n".join(lines).rstrip()


def section_diagnostics(diagnostics_dir):
    """Follow-up runs made to explain a hole, kept apart from the matrix.

    These deliberately run under conditions no other system was given, so they
    are never comparable with anything in raw/. Each file says so in its own
    `why` field, which is reproduced here rather than paraphrased.
    """
    if not os.path.isdir(diagnostics_dir):
        return None
    files = sorted(f for f in os.listdir(diagnostics_dir) if f.endswith(".json"))
    if not files:
        return None

    lines = [
        "## Diagnostics",
        "",
        "Follow-up runs that exist to explain an empty cell. **They are not "
        "benchmark results.** Each one was given conditions no other system "
        "was given, so none of them may be compared with the matrix above or "
        "aggregated into it.",
        "",
    ]
    for name in files:
        with open(os.path.join(diagnostics_dir, name)) as fh:
            diag = json.load(fh)
        outcome = diag.get("outcome", {})
        budget = diag.get("memory_budget", {})
        peaks = diag.get("peak_memory_bytes", {})
        lines += [
            f"### `{name}`",
            "",
            f"{diag.get('system')} · `{diag.get('profile')}` · "
            f"config {diag.get('config')} · concurrency {diag.get('concurrency')}",
            "",
            # Quoted verbatim from the diagnostic file. Angle brackets in it
            # are path placeholders, not markup, and markdown would eat them.
            "> " + diag.get("why", "").replace("<", "&lt;"),
            "",
            table(
                ["", ""],
                [["Memory budget",
                  f"{budget.get('diagnostic_requested')} for this run, against "
                  f"{budget.get('matrix_budget')} in the matrix"],
                 ["Completed", "yes" if outcome.get("completed") else "no"],
                 ["OOM-killed", "yes" if outcome.get("container_oom_killed") else "no"],
                 ["Peak memory",
                  ", ".join(f"{k} {v / 1024**3:.2f} GiB"
                            for k, v in sorted(peaks.items()))]],
            ),
            "",
        ]
    return "\n".join(lines).rstrip()


def section_reproduce(profile_id):
    return "\n".join([
        "## Reproducing this",
        "",
        "```sh",
        "python -m venv .venv && .venv/bin/pip install -r requirements-dev.txt",
        "bench/lock-images.sh               # re-resolve digests, exit 1 on drift",
        "bench/run.sh                       # the full matrix",
        "bench/make_results.py              # regenerate this file",
        "```",
        "",
        "`bench/run.sh` is resumable: a cell that already has a result file is "
        "skipped, so an interrupted matrix continues rather than restarts.",
        "",
        "Results from other hardware are welcome and land in their own "
        f"`results/<profile-id>/` directory alongside `{profile_id}`. See "
        "[CONTRIBUTING.md](CONTRIBUTING.md).",
    ])


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def render(root, profile_id):
    results_dir = os.path.join(root, "results", profile_id)
    with open(os.path.join(results_dir, "conformance.json")) as fh:
        conformance = json.load(fh)
    with open(os.path.join(results_dir, "durability.json")) as fh:
        durability = json.load(fh)
    runs = load_runs(os.path.join(results_dir, "raw"))
    workloads = load_workloads(root)
    hw = conformance["hardware_profile"]
    systems = systems_in(conformance["matrix"], durability)

    parts = [
        section_header(profile_id, hw, workloads, runs),
        section_conformance(conformance),
        section_durability(durability),
        section_performance(workloads, runs, systems),
        section_diagnostics(os.path.join(results_dir, "diagnostics")),
        section_reproduce(profile_id),
    ]
    return "\n\n".join(p for p in parts if p) + "\n"


def default_profile_id(root):
    results_dir = os.path.join(root, "results")
    candidates = sorted(
        name for name in os.listdir(results_dir)
        if os.path.isfile(os.path.join(results_dir, name, "conformance.json"))
    )
    if len(candidates) != 1:
        sys.exit("make_results: pass a profile-id; found %d in results/ (%s)"
                 % (len(candidates), ", ".join(candidates) or "none"))
    return candidates[0]


def main(argv):
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("profile_id", nargs="?")
    parser.add_argument("-o", "--output", default=os.path.join(root, "RESULTS.md"))
    args = parser.parse_args(argv)

    profile_id = args.profile_id or default_profile_id(root)
    markdown = render(root, profile_id)
    if args.output == "-":
        sys.stdout.write(markdown)
    else:
        with open(args.output, "w") as fh:
            fh.write(markdown)
        print(f"wrote {args.output} ({len(markdown.splitlines())} lines) "
              f"from results/{profile_id}/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
