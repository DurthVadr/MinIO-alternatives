def section_header(profile_id, hw, workloads, runs):
    host = hw["host"]
    runtime = hw["container_runtime"]
    planned = planned_run_count(workloads)
    lines = [
        "# Results",
        "",
        f"Hardware profile `{profile_id}` · fingerprint `{hw['fingerprint']}` · "
        f"captured {hw['captured_at']}.",
        "",
        "Generated by `bench/make_results.py` from the JSON under "
        f"`results/{profile_id}/`. Do not edit by hand.",
        "",
        "## What produced these numbers",
        "",
        table(
            ["", ""],
            [
                ["Host", f"{host['cpu_model']}, {host['cpu_cores']} cores, "
                         f"{host['ram_bytes'] / 1024**3:.0f} GB RAM, "
                         f"{host['os']} {host['os_version']} ({host['arch']})"],
                ["Container runtime", f"{runtime['kind']} {runtime['server_version']}, "
                                      f"VM {runtime['vm_cpus']} vCPU / "
                                      f"{runtime['vm_ram_bytes'] / 1024**3:.1f} GiB, "
                                      f"{runtime['storage_driver']}"],
                ["Load generator", f"warp {hw['warp']}"],
            ],
        ),
        "",
        "Image digests, which are what the systems under test actually were:",
        "",
        "```",
    ]
    for system in systems_in(hw["images"]):
        lines.append(f"{system:<10} {hw['images'][system]}")
    lines += [
        "```",
        "",
        f"**Coverage: {len(runs)} of {planned} planned measurement runs.** "
        "The conformance and durability matrices below are complete. The "
        "performance matrix is not, and the gap changes how it can be read — "
        "see [Performance](#performance).",
    ]
    return "\n".join(lines)


def planned_run_count(workloads):
    """Runs the full matrix would contain, from bench/workloads.yaml.

    profiles + the concurrency sweep, for every system and config, per round.
    """
    profiles = len(workloads["profiles"])
    sweep = len(workloads.get("sweep", {}).get("concurrency", []))
    rounds = workloads["rounds"]
    return len(SYSTEM_ORDER) * len(CONFIG_LABEL) * (profiles + sweep) * rounds


def section_conformance(conformance):
    matrix = conformance["matrix"]
    systems = systems_in(matrix)
    behaviours = sorted({b for cells in matrix.values() for b in cells})

    lines = [
        "## S3 conformance",
        "",
        f"{len(behaviours)} behaviours across {len(systems)} systems. "
        "Complete, and independent of the hardware it ran on.",
        "",
        "### The five outcomes",
        "",
        table(
            ["", "Status", "Meaning"],
            [[f"`{g}`", f"`{s}`", m] for g, s, m in STATUS_MEANING],
        ),
        "",
        "`accepted_not_enforced` has its own category on purpose. The "
        "difference between *this feature is missing, plan around it* and "
        "*you think you have a guarantee and you do not* is the most useful "
        "thing this matrix can tell you, and a pass/fail column would erase it.",
        "",
        "**There is deliberately no per-system score.** The categories are not "
        "commensurable, so a total rewards a system for accepting a request it "
        "should refuse. That is not hypothetical: at one point in this study "
        "RustFS ranked above MinIO for exactly that reason.",
        "",
        "### Matrix",
        "",
    ]

    rows = []
    for behaviour in behaviours:
        label = behaviour[5:] if behaviour.startswith("test_") else behaviour
        rows.append([f"`{label}`"] +
                    [STATUS_GLYPH.get(matrix[s].get(behaviour, {}).get("status"), "?")
                     for s in systems])
    lines.append(table(["Behaviour"] + systems, rows))

    tally_rows = []
    for system in systems:
        counts = {}
        for cell in matrix[system].values():
            counts[cell["status"]] = counts.get(cell["status"], 0) + 1
        tally_rows.append([system] + [counts.get(s, 0) or "—"
                                      for _, s, _ in STATUS_MEANING])
    lines += [
        "",
        "Counts per outcome, for reading the *shape* of a row rather than "
        "comparing totals:",
        "",
        table(["System"] + [f"`{s}`" for _, s, _ in STATUS_MEANING], tally_rows,
              right=set(range(1, len(STATUS_MEANING) + 1))),
        "",
        "### Every cell that is not `supported`",
        "",
        "The detail lines below are recorded by the test that produced the "
        "cell, at the moment it produced it.",
        "",
    ]

    for system in systems:
        divergent = [(b, c) for b, c in sorted(matrix[system].items())
                     if c["status"] != "supported"]
        if not divergent:
            lines += [f"**{system}** — every behaviour supported.", ""]
            continue
        lines += [f"**{system}**", ""]
        rows = []
        for behaviour, cell in divergent:
            label = behaviour[5:] if behaviour.startswith("test_") else behaviour
            detail = cell.get("detail", "")
            if cell.get("reason"):
                detail = f"({cell['reason']}) {detail}"
            rows.append([f"`{label}`", f"`{cell['status']}`", detail])
        lines += [table(["Behaviour", "Status", "What was observed"], rows), ""]

    return "\n".join(lines).rstrip()


def section_durability(durability):
    systems = systems_in(durability)
    rows = []
    for system in systems:
        entry = durability[system]
        rows.append([
            system,
            entry["mechanism"],
            "survived" if entry["fault_tolerated"] else "**lost the object**",
            f"{entry['usable_ratio']:.4f}",
        ])

    lines = [
        "## Durability",
        "",
        "Not asserted from configuration. For every system an object is "
        "written, a device is then actually destroyed, and the object is read "
        "back and compared byte for byte.",
        "",
        table(["System", "Mechanism", "One device lost", "Usable space"], rows,
              right={3}),
        "",
        "`Usable space` is measured, not derived: a known volume of objects is "
        "written and the bytes that land on the backing devices are counted. "
        "It is a result, not a control.",
        "",
        "**Fault tolerance is the axis held equal, and storage efficiency is "
        "what it costs.** Erasure coding and replication cannot be equalised "
        "on both at once. Every system here is configured to survive the loss "
        "of exactly one device, and the space that costs is the number in the "
        "last column: for the same guarantee, erasure coding leaves about 75% "
        "of raw capacity usable and 2-copy replication leaves 50%.",
        "",
        "### Past the redundancy limit",
        "",
        "A negative control: enough devices are destroyed that the data cannot "
        "be reconstructed, and the read is confirmed to fail. Without it, a "
        "passing durability test says nothing about whether the test can fail "
        "at all.",
        "",
        "Reads are then sampled on a fixed schedule — **t=0 is the moment the "
        "fault-injection command returns**, followed by samples at 0.25, 0.5, "
        "1, 2, 4 and 8 seconds. The counts below describe that schedule, not "
        "observed frequencies: a behaviour confined to a sub-second window "
        "appears once because only the earliest samples land inside it.",
        "",
    ]

    rows = []
    for system in systems:
        evidence = durability[system]["evidence"]
        outcomes = evidence.get("redundancy_limit_distinct_outcomes", {})
        rows.append([
            system,
            evidence.get("redundancy_limit_action", ""),
            "yes" if evidence.get("redundancy_limit_read_failed") else "**no**",
            ", ".join(f"`{k}` ×{v}" for k, v in sorted(outcomes.items())),
        ])
    lines += [
        table(["System", "What was destroyed", "Read failed", "Sampled outcomes"],
              rows),
        "",
        "None of the four fails cleanly in the first moments after the fault. "
        "The transient shapes differ — a wrong error code, a `Content-Length` "
        "that does not match the body, an error body that is not S3 XML — and "
        "they are worth knowing if a client of yours retries on them.",
    ]

    caveats = [(s, c) for s in systems for c in durability[s].get("configuration_caveats", [])]
    if caveats:
        lines += ["", "### Configuration caveats", "",
                  "Settings that had to be changed to get a comparable "
                  "measurement, recorded here rather than in prose so they "
                  "travel with the data.", ""]
        for system, caveat in caveats:
            lines += [f"**{system}** — `{caveat.get('setting', '')}`", ""]
            for label, key in (("Effect on the comparison", "effect_on_comparison"),
                               ("Finding", "finding"),
                               ("Also required", "also_required")):
                if caveat.get(key):
                    lines.append(f"- *{label}:* {caveat[key]}")
            lines.append("")

    return "\n".join(lines).rstrip()


